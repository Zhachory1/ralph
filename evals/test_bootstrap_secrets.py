"""The host-side step that fills in RALPH_WEBUI_API_KEY before Compose reads it.

Compose interpolates ${RALPH_WEBUI_API_KEY} on the host when it parses
docker-compose.yml, before any container starts, so this cannot be done by
anything that runs inside a container. `bootstrap/secrets` is the host script;
these tests run it as a subprocess against a throwaway directory, never
against the real compose/.env.

    python3 evals/test_bootstrap_secrets.py
"""

import pathlib
import subprocess
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "bootstrap" / "secrets"

EXAMPLE = """# Copy to .env and fill in. Never commit the result.

HERMES_VERSION=v0.22.2

# Shared secret (16+ chars). Generated by bootstrap/secrets.
RALPH_WEBUI_API_KEY=

RALPH_BOARD=ralph
"""


class BootstrapSecretsTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.dir = pathlib.Path(self.tmp.name)
        self.example = self.dir / ".env.example"
        self.env = self.dir / ".env"
        self.example.write_text(EXAMPLE)

    def tearDown(self):
        self.tmp.cleanup()

    def run_script(self):
        return subprocess.run(
            [str(SCRIPT), "--env", str(self.env), "--example", str(self.example)],
            capture_output=True, text=True)

    def key_value(self):
        for line in self.env.read_text().splitlines():
            if line.startswith("RALPH_WEBUI_API_KEY="):
                return line.split("=", 1)[1]
        self.fail("RALPH_WEBUI_API_KEY line missing from .env")

    def test_creates_env_from_example_when_missing(self):
        self.assertFalse(self.env.exists())
        self.run_script()
        self.assertTrue(self.env.exists())

    def test_generates_a_key_at_least_16_characters_when_blank(self):
        self.run_script()
        self.assertGreaterEqual(len(self.key_value()), 16)

    def test_does_not_change_an_existing_key(self):
        self.example.write_text(EXAMPLE.replace(
            "RALPH_WEBUI_API_KEY=", "RALPH_WEBUI_API_KEY=already-set-value"))
        self.run_script()
        self.assertEqual("already-set-value", self.key_value())

    def test_a_second_run_is_a_no_op(self):
        self.run_script()
        first = self.env.read_text()
        self.run_script()
        second = self.env.read_text()
        self.assertEqual(first, second)

    def test_other_lines_are_preserved(self):
        self.run_script()
        lines = self.env.read_text().splitlines()
        self.assertIn("# Copy to .env and fill in. Never commit the result.", lines)
        self.assertIn("HERMES_VERSION=v0.22.2", lines)
        self.assertIn("RALPH_BOARD=ralph", lines)

    def test_the_key_never_appears_in_output(self):
        result = self.run_script()
        key = self.key_value()
        self.assertNotIn(key, result.stdout)
        self.assertNotIn(key, result.stderr)

    def test_env_is_written_with_mode_600(self):
        self.run_script()
        self.assertEqual("600", oct(self.env.stat().st_mode)[-3:])


class MoreSecretsTests(BootstrapSecretsTests):
    """The dashboard password, and an .env older than the example."""

    def value(self, key):
        for line in self.env.read_text().splitlines():
            if line.startswith(f"{key}="):
                return line.split("=", 1)[1]
        return None

    def test_generates_the_dashboard_password_too(self):
        """The dashboard refuses to start without an auth provider, and a
        blank password is not one. Nobody should have to invent it."""
        self.run_script()
        self.assertGreaterEqual(len(self.value("RALPH_DASHBOARD_PASSWORD") or ""), 16)

    def test_the_two_secrets_are_different(self):
        self.run_script()
        self.assertNotEqual(self.value("RALPH_WEBUI_API_KEY"), self.value("RALPH_DASHBOARD_PASSWORD"))

    def test_adds_a_variable_a_newer_example_introduced(self):
        """An .env written before a release that introduced a required
        variable never gains it, and Compose then fails at parse time naming
        the variable but not where it should have come from. This is what
        happened the first time hermes-webui was started."""
        self.env.write_text("HERMES_VERSION=v0.22.2\nRALPH_BOARD=ralph\n")
        self.example.write_text(EXAMPLE + "HERMES_WEBUI_VERSION=0.52.458\n")
        result = self.run_script()
        self.assertEqual("0.52.458", self.value("HERMES_WEBUI_VERSION"))
        self.assertIn("added HERMES_WEBUI_VERSION", result.stdout)

    def test_an_added_variable_does_not_overwrite_one_already_set(self):
        self.env.write_text("HERMES_VERSION=v0.99.0\n")
        self.run_script()
        self.assertEqual("v0.99.0", self.value("HERMES_VERSION"))

    def test_neither_secret_appears_in_output(self):
        result = self.run_script()
        for key in ("RALPH_WEBUI_API_KEY", "RALPH_DASHBOARD_PASSWORD"):
            self.assertNotIn(self.value(key), result.stdout + result.stderr)


if __name__ == "__main__":
    unittest.main(verbosity=2)
